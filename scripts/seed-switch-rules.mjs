#!/usr/bin/env node
/**
 * 第23弾: 乗り換えルール投入SQL生成。
 *
 * hozenkun-assistant/master/switch-rules.json(単一の真実)を読み、
 * insurance_switch_rules への冪等な upsert SQL を生成する。
 * 生成した .sql は `wrangler d1 execute <db名> --remote --file=...` で流す。
 *
 * 使い方(リポジトリルートで):
 *   node scripts/seed-switch-rules.mjs [switch-rules.jsonのパス] [-o 出力先.sql]
 *
 * 既定値:
 *   入力: ../../hozenkun-assistant/master/switch-rules.json (リポジトリルート基準)
 *   出力: migrations-data/048_switch_rules_data.sql
 *
 * 検証(いずれか失敗で生成せず異常終了):
 *   - old_product_id / new_product_id が products.json(同じフォルダ)に実在すること
 *   - old と new が同一でないこと
 *   - id が採番規則 swr_ + sha1(old + "->" + new) 先頭12桁 と一致すること
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_INPUT = join(REPO_ROOT, '..', '..', 'hozenkun-assistant', 'master', 'switch-rules.json');
const DEFAULT_OUTPUT = join(REPO_ROOT, 'migrations-data', '048_switch_rules_data.sql');

// JST の既定値式(schema の created_at 規約と同一)
const JST_NOW_SQL = "strftime('%Y-%m-%dT%H:%M:%f', 'now', '+9 hours')";

function parseArgs(argv) {
  let input = DEFAULT_INPUT;
  let output = DEFAULT_OUTPUT;
  const rest = [...argv];
  while (rest.length > 0) {
    const arg = rest.shift();
    if (arg === '-o' || arg === '--output') {
      output = resolve(rest.shift() ?? '');
    } else if (arg === '-h' || arg === '--help') {
      console.log('usage: node scripts/seed-switch-rules.mjs [switch-rules.json] [-o out.sql]');
      process.exit(0);
    } else {
      input = resolve(arg);
    }
  }
  return { input, output };
}

const sqlQuote = (value) => `'${String(value).replace(/'/g, "''")}'`;

/** 採番規則: swr_ + sha1(old_product_id + "->" + new_product_id) の先頭12桁 */
const expectedRuleId = (oldId, newId) =>
  `swr_${createHash('sha1').update(`${oldId}->${newId}`, 'utf8').digest('hex').slice(0, 12)}`;

const { input, output } = parseArgs(process.argv.slice(2));

const master = JSON.parse(readFileSync(input, 'utf8'));
if (!Array.isArray(master.rules)) {
  throw new Error(`rules 配列がありません: ${input}`);
}

// old/new の実在検証は同じフォルダの products.json(単一の真実)に対して行う
const productsPath = join(dirname(input), 'products.json');
const products = JSON.parse(readFileSync(productsPath, 'utf8'));
const productById = new Map(products.products.map((p) => [p.id, p]));
const categoryById = new Map(products.categories.map((c) => [c.id, c.name]));
const companyById = new Map(products.companies.map((c) => [c.id, c.name]));

const describeProduct = (id) => {
  const p = productById.get(id);
  return `${companyById.get(p.company_id) ?? '?'} ${p.product_name}(${categoryById.get(p.category_id) ?? '?'})`;
};

const seenIds = new Set();
const statements = [];
for (const rule of master.rules) {
  if (!productById.has(rule.old_product_id)) {
    throw new Error(`old_product_id が products.json に存在しません: ${rule.old_product_id} (${rule.id})`);
  }
  if (!productById.has(rule.new_product_id)) {
    throw new Error(`new_product_id が products.json に存在しません: ${rule.new_product_id} (${rule.id})`);
  }
  if (rule.old_product_id === rule.new_product_id) {
    throw new Error(`old と new が同一です: ${rule.id}`);
  }
  const expected = expectedRuleId(rule.old_product_id, rule.new_product_id);
  if (rule.id !== expected) {
    throw new Error(`id が採番規則と一致しません: ${rule.id} (期待値: ${expected})`);
  }
  if (seenIds.has(rule.id)) {
    throw new Error(`id が重複しています: ${rule.id}`);
  }
  seenIds.add(rule.id);

  // 第26弾(二層方式)の保護:
  // - 新規INSERTは source='master', is_active=1
  // - 既存行へのupsertは is_active を上書きしない(ユーザーの無効化を尊重)。
  //   source は 'master' に揃える(同一ペアのcustomルールがあった場合はmasterに昇格し、
  //   以後seed管理下になる — IDが old->new から決定的なため同一ペア=同一ID)
  statements.push(
    `-- ${describeProduct(rule.old_product_id)} → ${describeProduct(rule.new_product_id)}\n` +
      `INSERT INTO insurance_switch_rules (id, old_product_id, new_product_id, memo, source, is_active, created_at, updated_at)\n` +
      `VALUES (${sqlQuote(rule.id)}, ${sqlQuote(rule.old_product_id)}, ${sqlQuote(rule.new_product_id)}, ${rule.memo == null ? 'NULL' : sqlQuote(rule.memo)}, 'master', 1, ${JST_NOW_SQL}, ${JST_NOW_SQL})\n` +
      `ON CONFLICT(id) DO UPDATE SET\n` +
      `  old_product_id = excluded.old_product_id,\n` +
      `  new_product_id = excluded.new_product_id,\n` +
      `  memo = excluded.memo,\n` +
      `  source = 'master',\n` +
      `  updated_at = excluded.updated_at;`,
  );
}

// マスターから消えたルールは削除する — ただし source='master' の行だけが対象。
// 管理画面で作った custom 行には一切触れない(第26弾の二層方式)。
const cleanup =
  statements.length > 0
    ? `DELETE FROM insurance_switch_rules WHERE source = 'master' AND id NOT IN (${[...seenIds].map(sqlQuote).join(', ')});`
    : `DELETE FROM insurance_switch_rules WHERE source = 'master';`;

const header = [
  '-- Generated by scripts/seed-switch-rules.mjs — 手で編集しない。',
  '-- 入力: hozenkun-assistant/master/switch-rules.json (単一の真実)',
  `-- 件数: ${master.rules.length} ルール`,
  '-- 冪等: 何度流しても同じ結果になる(upsert + マスター外の削除)。',
  '-- 二層方式(第26弾): 対象は source=\'master\' の行のみ。管理画面で作ったcustom行には触れず、',
  '-- is_active も上書きしない(ユーザーの無効化はseed再投入後も維持される)。',
  '',
].join('\n');

const sql = `${header}${statements.join('\n\n')}\n\n${cleanup}\n`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, sql, 'utf8');
console.log(`written: ${output}`);
console.log(`rules: ${master.rules.length}`);
