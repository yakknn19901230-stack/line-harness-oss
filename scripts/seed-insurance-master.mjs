#!/usr/bin/env tsx
/**
 * 第21弾: 保険商品マスター投入SQL生成。
 *
 * hozenkun-assistant/master/products.json(単一の真実)を読み、
 * insurance_products への冪等な upsert SQL を生成する。
 * 生成した .sql は `wrangler d1 execute <db名> --remote --file=...` で流す。
 *
 * 使い方(リポジトリルートで):
 *   npx tsx scripts/seed-insurance-master.mjs [products.jsonのパス] [-o 出力先.sql]
 *
 * 既定値:
 *   入力: ../../hozenkun-assistant/master/products.json (リポジトリルート基準)
 *   出力: packages/db/seeds/insurance-master.sql
 *
 * normalized_name は packages/shared の normalizeForMatch(insurance-assistant の
 * normalize_for_match_text と同値)で生成する。TS ソースを直接 import するため
 * node ではなく tsx で実行すること。
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as insuranceModule from '../packages/shared/src/insurance.ts';

// tsx の ESM/CJS ブリッジは .mjs からの named import を解決できないことがあるため
// 名前空間 import から取り出す(default 側に入るケースも吸収)。
const normalizeForMatch =
  insuranceModule.normalizeForMatch ?? insuranceModule.default?.normalizeForMatch;
if (typeof normalizeForMatch !== 'function') {
  throw new Error('normalizeForMatch を packages/shared/src/insurance.ts から読み込めませんでした');
}

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_INPUT = join(REPO_ROOT, '..', '..', 'hozenkun-assistant', 'master', 'products.json');
const DEFAULT_OUTPUT = join(REPO_ROOT, 'packages', 'db', 'seeds', 'insurance-master.sql');

// JST の既定値式(schema の created_at 規約と同一)
const JST_NOW_SQL = "strftime('%Y-%m-%dT%H:%M:%f', 'now', '+9 hours')";

function parseArgs(argv) {
  let input = DEFAULT_INPUT;
  let output = DEFAULT_OUTPUT;
  const rest = [...argv];
  while (rest.length > 0) {
    const arg = rest.shift();
    if (arg === '-o' || arg === '--output') {
      output = resolve(rest.shift() ?? '');
    } else if (arg === '-h' || arg === '--help') {
      console.log('usage: npx tsx scripts/seed-insurance-master.mjs [products.json] [-o out.sql]');
      process.exit(0);
    } else {
      input = resolve(arg);
    }
  }
  return { input, output };
}

const sqlQuote = (value) => `'${String(value).replace(/'/g, "''")}'`;

const { input, output } = parseArgs(process.argv.slice(2));

const master = JSON.parse(readFileSync(input, 'utf8'));
const categories = new Map(master.categories.map((c) => [c.id, c]));
const companies = new Map(master.companies.map((c) => [c.id, c]));

const statements = [];
const ids = [];
for (const product of master.products) {
  const category = categories.get(product.category_id);
  const company = companies.get(product.company_id);
  if (!category) throw new Error(`unknown category_id: ${product.category_id} (${product.product_name})`);
  if (!company) throw new Error(`unknown company_id: ${product.company_id} (${product.product_name})`);
  ids.push(product.id);
  statements.push(
    `INSERT INTO insurance_products (id, category_name, company_name, product_name, normalized_name, is_active, created_at, updated_at)\n` +
      `VALUES (${sqlQuote(product.id)}, ${sqlQuote(category.name)}, ${sqlQuote(company.name)}, ${sqlQuote(product.product_name)}, ${sqlQuote(normalizeForMatch(product.product_name))}, 1, ${JST_NOW_SQL}, ${JST_NOW_SQL})\n` +
      `ON CONFLICT(id) DO UPDATE SET\n` +
      `  category_name = excluded.category_name,\n` +
      `  company_name = excluded.company_name,\n` +
      `  product_name = excluded.product_name,\n` +
      `  normalized_name = excluded.normalized_name,\n` +
      `  is_active = 1,\n` +
      `  updated_at = excluded.updated_at;`,
  );
}

// マスターから消えた商品は無効化する(削除はしない: friend_contracts 等からの参照を守る)
const deactivate =
  `UPDATE insurance_products SET is_active = 0, updated_at = ${JST_NOW_SQL}\n` +
  `WHERE id NOT IN (${ids.map(sqlQuote).join(', ')});`;

const header = [
  '-- Generated by scripts/seed-insurance-master.mjs — 手で編集しない。',
  `-- 入力: hozenkun-assistant/master/products.json (単一の真実)`,
  `-- 件数: ${master.products.length} 商品 / ${master.companies.length} 社 / ${master.categories.length} 種類`,
  '-- 冪等: 何度流しても同じ結果になる(upsert + マスター外の無効化)。',
  '',
].join('\n');

const sql = `${header}${statements.join('\n\n')}\n\n${deactivate}\n`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, sql, 'utf8');
console.log(`written: ${output}`);
console.log(`products: ${master.products.length}, companies: ${master.companies.length}, categories: ${master.categories.length}`);
